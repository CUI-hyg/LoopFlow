"""``loopflow init`` 子命令 — 脚手架初始化。

在目标路径生成 Loop Engineering 所需的文件结构：

- ``LOOP.md``：循环配置文档（活跃循环列表、节奏、级别、worktree 策略）
- ``STATE.md``：初始状态文件（当前迭代、待办、已完成、暂停标志）
- ``loop-budget.yaml``：预算配置（daily_cap, threshold 等）
- ``loop-constraints.md``：约束文件（路径保护、行为规则）
- ``.claude/skills/loop-triage/SKILL.md``（仅 ``--tool claude`` 时生成）

用法::

    loopflow init                          # 在当前目录初始化（默认 daily-triage / claude / L1）
    loopflow init /tmp/proj --pattern daily-triage --tool claude --level L1
"""

from __future__ import annotations

from pathlib import Path

import click
from rich.console import Console

from loopkits.cli.audit import run_audit
from loopkits.core.loop import TrustLevel
from loopkits.patterns.registry import get, list_patterns

__all__ = ["init"]

console: Console = Console()


def _render_loop_md(
    pattern_name: str,
    level: str,
    tool: str,
    cadence: str,
    description: str,
) -> str:
    """生成 LOOP.md 内容。"""
    return f"""# LOOP.md — {pattern_name}

This file documents how this project is operated with Loop Engineering patterns.
Generated by `loopflow init`.

## Active Loops

### {pattern_name} ({level} — {('automated + report' if level == 'L1' else 'assisted' if level == 'L2' else 'full auto')})
- Cadence: {cadence or '1d'}
- Pattern: `{pattern_name}` — {description}
- State: `STATE.md` (updated by loop on each run; human reviews periodically)
- Tool: `{tool}`
- Phase: {('Report-only. Human reviews and decides actions.' if level == 'L1' else 'Assisted fixes in worktree; verifier required; no auto-merge.' if level == 'L2' else 'Full auto with strict constraints and verifier gates.')}
- Handoff: Design decisions, large refactors, new pattern acceptance.

## Multi-loop coordination

If running multiple loops, priority order:
CI Sweeper → PR Babysitter → Dependency Sweeper → Post-Merge / Changelog Drafter (off-peak) → Daily Triage (report).

## Worktrees

- Any unattended code-change experiment runs in an **isolated git worktree** per attempt.
- One worktree per fix; discard after verifier REJECT or human escalation.
- Use `loopflow worktree create --run-id <id> --pattern {pattern_name}` to create a worktree.

## Budget & Observability

- Token caps: `loop-budget.yaml`
- Run history: appended to `STATE.md` by the loop on each run
- Estimate: `loopflow cost {pattern_name} --runs 10`
- Kill switch: `loop-pause-all` flag in `STATE.md` (set via `loopflow state pause`)

## Safety & Gates

- No auto-merge on main except trivial dependency patches (allowlist + verifier)
- Denylist: see `loop-constraints.md`
- Live loop state: `STATE.md` at repo root

## How to run locally

```bash
loopflow run {pattern_name} --level {level}
loopflow audit . --suggest
loopflow state show
```

---

*This file is both documentation and the seed for the loops that maintain this project.*
"""


